# `class Gluten<X> extends <X> with <Trait>[ with <Trait>...] {}`, optionally
# preceded by annotations. Tolerates line breaks inside the declaration.
SHELL_RE = re.compile(
    r"(?P<anns>(?:^[ \t]*@[\w.]+(?:\([^)]*\))?[ \t]*\r?\n)*)"
    r"^[ \t]*(?:final[ \t]+)?class[ \t]+(?P<cls>\w+)\s+extends\s+(?P<base>[\w.]+)"
    r"(?P<withs>(?:\s+with\s+[\w.]+)+)\s*\{\s*\}[ \t]*$",
    re.M,
)
DECL_RE = re.compile(
    r"^[ \t]*(?:(?:abstract|final|sealed|implicit|private|protected)[ \t]+)*"
    r"(class|trait|object|case[ \t]+class|case[ \t]+object)[ \t]+(\w+)",
    re.M,
)
PACKAGE_RE = re.compile(r"^package\s+([\w.]+)\s*$", re.M)
IMPORT_RE = re.compile(r"^import\s+([\w.]+)\s*$", re.M)
STRING_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def strip_comments(text):
    """Remove // and /* */ comments, keeping line structure (and string literals)."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            m = STRING_RE.match(text, i)
            if m:
                out.append(m.group(0))
                i = m.end()
                continue
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i)
            chunk = text[i: n if j < 0 else j + 2]
            out.append("\n" * chunk.count("\n"))
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def parse_string_args(args):
    """Scala argument list -> list of string values.

    Splits on top-level commas and concatenates the literals within each argument,
    so a name written across lines as `"SPARK-19471: ..." + " before using it"` stays
    one name.
    """
    values, current, depth, i, n = [], [], 0, 0, len(args)
    while i < n:
        c = args[i]
        if c == '"':
            m = STRING_RE.match(args, i)
            if not m:
                raise SystemExit("unterminated string literal in: %s" % args)
            current.append(unescape(m.group(1)))
            i = m.end()
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            values.append("".join(current))
            current = []
        i += 1
    if current:
        values.append("".join(current))
    return values


def unescape(s):
    return (
        s.replace(r"\"", '"')
        .replace(r"\\", "\\")
        .replace(r"\n", "\n")
        .replace(r"\t", "\t")
    )


def scala_files(root):
    for dirpath, _, names in os.walk(root):
        for name in sorted(names):
            if name.endswith(".scala"):
                yield os.path.join(dirpath, name)


def scan_symbols(roots):
    """simple name -> set of fully qualified names, for every type under `roots`.

    A name declared in more than one package is kept as a set: scalac forces the
    Scala source to qualify such a reference, so `resolve` refuses to guess.
    """
    symbols = {}
    for root in roots:
        if not os.path.isdir(root):
            continue
        for path in scala_files(root):
            text = open(path, encoding="utf-8").read()
            pkg_m = PACKAGE_RE.search(text)
            if not pkg_m:
                continue
            pkg = pkg_m.group(1)
            for _, name in DECL_RE.findall(strip_comments(text)):
                symbols.setdefault(name, set()).add("%s.%s" % (pkg, name))
    return symbols


class Shell(object):
    """A generatable `class GlutenX extends X with T {}` declaration.

    `pkg` is where the generated class goes, which is usually -- but not always --
    the package of the suite it extends.
    """

    def __init__(self, pkg, cls, base_fqn, traits, anns, alt_base_pkgs=()):
        self.pkg, self.cls, self.base_fqn = pkg, cls, base_fqn
        self.traits, self.anns = traits, anns
        # Other packages the base class could have come from, when the source
        # referred to it through a wildcard import. Reported by `extract`.
        self.alt_base_pkgs = list(alt_base_pkgs)

    @property
    def base_pkg(self):
        return self.base_fqn.rsplit(".", 1)[0]


def find_shells(path, text, symbols=None):
    """Return (shells, total_decl_count) for one file.

    Trait and annotation names are fully qualified where possible: from the
    file's own imports first, then from `symbols` (types declared in gluten-ut),
    so the catalog does not depend on which package a generated class lands in.
    """
    pkg_m = PACKAGE_RE.search(text)
    if not pkg_m:
        return [], 0
    pkg = pkg_m.group(1)
    imports = {fqn.rsplit(".", 1)[-1]: fqn for fqn in IMPORT_RE.findall(text)}
    wildcards = [
        m.group(1) for m in re.finditer(r"^import\s+([\w.]+)\._\s*$", text, re.M)
    ]

    def qualify(name):
        if "." in name:
            return name
        if name in imports:
            return imports[name]
        candidates = (symbols or {}).get(name, set())
        if len(candidates) == 1:
            return next(iter(candidates))
        return name  # same-package or out of scope; leave as written

    total = len(DECL_RE.findall(strip_comments(text)))
    shells = []
    for m in SHELL_RE.finditer(text):
        cls, base = m.group("cls"), m.group("base")
        simple_base = base.rsplit(".", 1)[-1]
        if cls != "Gluten" + simple_base:
            continue  # non-conventional name: leave hand-written
        # The base class is usually in this file's package, but a handful of shells
        # import it from elsewhere. Generated code always qualifies it, so a wrong
        # guess here shows up as a compile error rather than a bad catalog entry.
        alternatives = []
        if "." in base:
            base_fqn = base
        elif base in imports:
            base_fqn = imports[base]
        else:
            base_fqn = "%s.%s" % (pkg, base)
            alternatives = [w for w in wildcards if w != pkg]
        traits = [qualify(t) for t in re.findall(r"with\s+([\w.]+)", m.group("withs"))]
        anns = [qualify(a) for a in re.findall(r"@([\w.]+)", m.group("anns") or "")]
        shells.append(Shell(pkg, cls, base_fqn, traits, anns, alternatives))
    return shells, total


# ---------------------------------------------------------------------------
# Catalog (suites.txt)
# ---------------------------------------------------------------------------
# One line per generated suite:
#     <vanilla suite FQN> | <trait FQN>[,...] [| ann=<FQN>[,...]] [| pkg=<package>]
# The generated class is <vanilla package>.Gluten<vanilla simple name> unless `pkg=`
# says otherwise.


def catalog_line(shell):
    line = "%s | %s" % (shell.base_fqn, ",".join(shell.traits))
    if shell.anns:
        line += " | ann=%s" % ",".join(shell.anns)
    if shell.pkg != shell.base_pkg:
        line += " | pkg=%s" % shell.pkg
    return line


def parse_catalog(path):
    entries = []
    for lineno, raw in enumerate(open(path, encoding="utf-8"), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 2:
            raise SystemExit("%s:%d: expected '<suite> | <traits>': %s" % (path, lineno, line))
        base_fqn, traits = parts[0], [t for t in parts[1].split(",") if t]
        options = {}
        for extra in parts[2:]:
            if "=" not in extra:
                raise SystemExit("%s:%d: expected 'key=value', got '%s'" % (path, lineno, extra))
            key, value = extra.split("=", 1)
            options[key.strip()] = value.strip()
        unknown = set(options) - {"ann", "pkg"}
        if unknown:
            raise SystemExit("%s:%d: unknown option(s) %s" % (path, lineno, sorted(unknown)))
        base_pkg, simple = base_fqn.rsplit(".", 1)
        anns = [a for a in options.get("ann", "").split(",") if a]
        entries.append(
            Shell(options.get("pkg", base_pkg), "Gluten" + simple, base_fqn, traits, anns)
        )
    return entries


def render_shell(shell):
    body = [LICENSE, "", GEN_MARKER, "package %s" % shell.pkg, ""]
    for ann in shell.anns:
        body.append("@%s" % ann)
    body.append(
        "class %s extends %s with %s {}"
        % (shell.cls, shell.base_fqn, " with ".join(shell.traits))
    )
    return "\n".join(body) + "\n"


# ---------------------------------------------------------------------------
# Backend settings (settings-<backend>.txt)
# ---------------------------------------------------------------------------
# One directive per line. `#` at the start of a line is a comment; reasons for an
# exclusion are kept as comments directly above it, as they are in the Scala today.
#
#     enable          <suite FQN>
#     disable         <suite FQN> -- <reason>
#     exclude         <suite FQN>#<test name>
#     excludePrefix   <suite FQN>#<test name prefix>
#     include         <suite FQN>#<test name>
#     includePrefix   <suite FQN>#<test name prefix>
#     excludeGluten   <suite FQN>#<test name>        ("Gluten - " prefixed test)
#     includeGluten   <suite FQN>#<test name>
#     excludeGlutenPrefix <suite FQN>#<test name prefix>
#     includeAllGluten    <suite FQN>

DSL_TO_DIRECTIVE = {
    "exclude": "exclude",
    "excludeCH": "exclude",
    "excludeByPrefix": "excludePrefix",
    "include": "include",
    "includeCH": "include",
    "includeByPrefix": "includePrefix",
    "excludeGlutenTest": "excludeGluten",
    "includeGlutenTest": "includeGluten",
    "excludeGlutenTestsByPrefix": "excludeGlutenPrefix",
    "includeGlutenTestsByPrefix": "includeGlutenPrefix",
    "excludeAllGlutenTests": "excludeAllGluten",
    "includeAllGlutenTests": "includeAllGluten",
}
SUITE_ONLY_DIRECTIVES = {"enable", "excludeAllGluten", "includeAllGluten"}

STMT_START_RE = re.compile(r"^\s*(enableSuite|disableSuite|\.[a-zA-Z])")
ENABLE_RE = re.compile(r"^enableSuite(?:\[(?P<tag>[\w.]+)\]|\((?P<str>.*?)\))")
DISABLE_RE = re.compile(r"^disableSuite(?:\[(?P<tag>[\w.]+)\]|\((?P<str>[^,]*?),)")
CALL_RE = re.compile(r"\.(?P<name>[a-zA-Z]+)\((?P<args>.*?)\)\s*$", re.S)

IGNORABLE_RE = re.compile(
    r"^\s*(package\s|import\s|//|/\*|\*|class\s+\w+TestSettings|"
    r"override\s+def\s+getSQLQueryTestSettings|\}|\)|$)"
)


def logical_statements(lines):
    """Group physical lines into DSL statements, yielding (start_line, text)."""
    i, n = 0, len(lines)
    while i < n:
        if STMT_START_RE.match(lines[i]):
            start, buf, depth = i, [], 0
            while i < n:
                buf.append(lines[i])
                depth += lines[i].count("(") - lines[i].count(")")
                i += 1
                if depth <= 0:
                    break
            yield start, "\n".join(buf)
        else:
            yield i, None
            i += 1


def parse_settings(path, symbols):
    """Parse a *TestSettings.scala into ordered (directive, suite, arg, comments)."""
    text = open(path, encoding="utf-8").read()
    lines = text.split("\n")
    entries, pending, unconsumed = [], [], []
    calls_consumed = [0]
    current = None

    def resolve(name):
        if "." in name:
            return name
        candidates = symbols.get(name, set())
        if not candidates:
            raise SystemExit("%s: cannot resolve suite class '%s'" % (path, name))
        if len(candidates) > 1:
            raise SystemExit(
                "%s: '%s' is declared in %s -- qualify it in the Scala source"
                % (path, name, sorted(candidates))
            )
        return next(iter(candidates))

    for start, stmt in logical_statements(lines):
        if stmt is None:
            line = lines[start]
            stripped = line.strip()
            if stripped.startswith("//"):
                comment = stripped[2:].strip()
                if comment and not comment.startswith("scalastyle:"):
                    pending.append(comment)
            elif re.match(r"\s*class\s+\w+TestSettings", line):
                pending = []  # file-level notes, not a reason for a directive
            elif not IGNORABLE_RE.match(line):
                unconsumed.append((start + 1, line))
            continue

        body = strip_comments(stmt).strip()
        m = ENABLE_RE.match(body)
        if m:
            name = m.group("tag") or unescape(STRING_RE.search(m.group("str")).group(1))
            current = resolve(name)
            entries.append(("enable", current, None, pending))
            pending = []
            body = body[m.end():].strip()
        else:
            m = DISABLE_RE.match(body)
            if m:
                name = m.group("tag") or unescape(STRING_RE.search(m.group("str")).group(1))
                suite = resolve(name)
                reason = " ".join(
                    unescape(s) for s in STRING_RE.findall(body[m.end():])
                ).strip()
                entries.append(("disable", suite, reason, pending))
                pending, current = [], None
                continue

        # Chained .exclude(...) / .include(...) calls on the current suite.
        while body:
            call = CALL_RE.search(body)
            if not call:
                if body.strip():
                    unconsumed.append((start + 1, body))
                break
            name, args = call.group("name"), call.group("args")
            if name not in DSL_TO_DIRECTIVE:
                unconsumed.append((start + 1, ".%s(...)" % name))
                break
            if current is None:
                raise SystemExit("%s:%d: .%s() without an enabled suite" % (path, start + 1, name))
            directive = DSL_TO_DIRECTIVE[name]
            calls_consumed[0] += 1
            values = [v for v in parse_string_args(args) if v]
            if not values:
                entries.append((directive, current, None, pending))
            else:
                for idx, value in enumerate(values):
                    entries.append((directive, current, value, pending if idx == 0 else []))
            pending = []
            body = body[: call.start()].strip()

    return entries, unconsumed, calls_consumed[0]


def render_settings(entries, backend, spark):
    out = [
        DATA_HEADER,
        "# Gluten unit test settings for the %s backend, Spark %s." % (backend, spark),
        "#",
        "# Read at run time by org.apache.gluten.utils.DataFileBackendTestSettings.",
        "# One directive per line; see tools/scripts/gluten-ut/ut_suites.py for the format.",
        "#",
        "#   enable <suite>                     run this suite",
        "#   disable <suite> -- <reason>        never run it",
        "#   exclude <suite>#<test>             run the suite except this test",
        "#   excludePrefix <suite>#<prefix>     ...except tests starting with <prefix>",
        "#   include <suite>#<test>             run only this test (mutually exclusive",
        "#                                      with exclude, per suite)",
        "#",
        "# A test name is everything after the first '#'. Comment lines directly above a",
        "# directive are its reason, and are preserved by the extractor.",
        "",
    ]
    width = max(
        [len(d) for d, _, _, _ in entries] + [len("excludeGlutenPrefix")]
    )
    for directive, suite, arg, comments in entries:
        if directive == "enable":
            out.append("")
        for comment in comments:
            out.append("# %s" % comment)
        pad = directive.ljust(width)
        if directive == "disable":
            out.append("%s %s -- %s" % (pad, suite, arg))
        elif arg is None:
            out.append("%s %s" % (pad, suite))
        else:
            out.append("%s %s#%s" % (pad, suite, arg))
    return "\n".join(out).strip() + "\n"


