"""gluten-ut suite tooling.

Gluten runs vanilla Spark test suites by declaring, for each one, a subclass that
mixes in a Gluten test trait:

    class GlutenBucketingUtilsSuite extends BucketingUtilsSuite with GlutenSQLTestsBaseTrait {}

...and by registering that subclass, plus the tests to skip, in a per-backend
`BackendTestSettings` written in Scala. Both are pure boilerplate that has to be
duplicated for every supported Spark version. This script replaces them with two
data files per Spark version:

    src/test/resources/gluten-ut/suites.txt            the suite catalog
    src/test/resources/gluten-ut/settings-<backend>.txt what to run, per backend

`generate` turns the catalog into the subclasses at build time (nothing to commit,
nothing to review); the settings file is read at run time by
`org.apache.gluten.utils.DataFileBackendTestSettings`.

Subcommands
    extract   Scala sources -> data files (one-shot migration, per Spark version).
    generate  Catalog -> Scala sources under target/generated-test-sources.
              Run by maven; safe to run by hand.
    verify    Generate in memory and diff against the hand-written sources, to
              prove a migration is behaviour-preserving before deleting them.

Standard library only, python3.6+.
"""

