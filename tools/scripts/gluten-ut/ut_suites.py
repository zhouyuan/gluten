def cmd_extract(args):
    module = args.module.rstrip("/")
    scala_root = os.path.join(module, "src/test/scala")
    out_dir = os.path.join(module, "src/test/resources/gluten-ut")
    os.makedirs(out_dir, exist_ok=True)
    symbols = scan_symbols([scala_root, os.path.join(module, "../common/src/test/scala")])

    # 1. Catalog: every conventional shell in a file that contains nothing else.
    shells, mixed, skipped_files = [], [], []
    for path in scala_files(scala_root):
        text = open(path, encoding="utf-8").read()
        found, total = find_shells(path, text, symbols)
        if not found:
            continue
        if len(found) == total:
            shells.extend(found)
            skipped_files.append(path)
        else:
            mixed.extend(found)

    shells.sort(key=lambda s: s.base_fqn)
    catalog_path = os.path.join(out_dir, "suites.txt")

    # Re-running extract must not undo a correction made to the catalog by hand
    # (the base package of a suite reached through a wildcard import cannot always
    # be inferred), and must not lose entries whose sources have already been
    # pruned. Both are covered by carrying the existing catalog forward.
    if os.path.exists(catalog_path):
        previous = parse_catalog(catalog_path)
        by_gen = {"%s.%s" % (s.pkg, s.cls): s for s in shells}
        for old in previous:
            gen_fqn = "%s.%s" % (old.pkg, old.cls)
            found = by_gen.get(gen_fqn)
            if found is None:
                shells.append(old)  # source already pruned
            elif found.base_fqn != old.base_fqn and found.alt_base_pkgs:
                found.base_fqn = old.base_fqn  # keep the reviewed package
        shells.sort(key=lambda s: s.base_fqn)

    # Everything is parsed before anything is written, so a failure below cannot
    # leave a half-migrated data file behind.
    settings_files = []
    for backend in args.backends:
        cls = {"velox": "Velox", "clickhouse": "ClickHouse", "bolt": "Bolt"}[backend]
        if args.settings_scala:
            if len(args.backends) != 1:
                raise SystemExit("--settings-scala needs exactly one --backends value")
            settings_scala = args.settings_scala
        else:
            settings_scala = os.path.join(
                scala_root, "org/apache/gluten/utils", backend, "%sTestSettings.scala" % cls
            )
        if not os.path.exists(settings_scala):
            print("  skip %s: %s not found" % (backend, settings_scala))
            continue
        catalog_symbols = dict(symbols)
        for shell in shells:
            catalog_symbols.setdefault(shell.cls, set()).add("%s.%s" % (shell.pkg, shell.cls))
        entries, unconsumed, calls_consumed = parse_settings(settings_scala, catalog_symbols)
        if unconsumed:
            print("  ERROR: %d unparsed line(s) in %s:" % (len(unconsumed), settings_scala))
            for lineno, line in unconsumed[:20]:
                print("    %d: %s" % (lineno, line.strip()))
            return 1
        settings_files.append((backend, settings_scala, entries, calls_consumed))

    with open(catalog_path, "w", encoding="utf-8") as fh:
        fh.write(DATA_HEADER + "\n")
        fh.write("# Vanilla Spark suites that Gluten runs through a generated subclass:\n")
        fh.write("#\n")
        fh.write("#   <vanilla suite> | <trait>[,<trait>...] [| <annotation>,...]\n")
        fh.write("#\n")
        fh.write("# generates, at build time (see tools/scripts/gluten-ut/ut_suites.py):\n")
        fh.write("#\n")
        fh.write("#   class Gluten<Suite> extends <Suite> with <trait> {}\n")
        fh.write("#\n")
        fh.write("# Whether a generated suite actually runs is decided per backend, in\n")
        fh.write("# settings-<backend>.txt.\n\n")
        for shell in shells:
            fh.write(catalog_line(shell) + "\n")
    print("catalog: %s (%d suites, from %d files)" % (catalog_path, len(shells), len(skipped_files)))
    ambiguous = [s for s in shells if s.alt_base_pkgs]
    if ambiguous:
        print(
            "  %d suite(s) reached their base class through a wildcard import; the catalog\n"
            "  assumed the same package. A wrong guess is a compile error, not a silent\n"
            "  mistake -- check these, and correct the line if the build complains:"
            % len(ambiguous)
        )
        for shell in ambiguous:
            print(
                "    %s  (or: %s)"
                % (shell.base_fqn, ", ".join("%s.%s" % (p, shell.base_fqn.rsplit(".", 1)[-1])
                                             for p in shell.alt_base_pkgs))
            )
    if mixed:
        print(
            "  %d shell(s) left hand-written: declared in a file that holds other code too"
            % len(mixed)
        )

    # 2. Per-backend settings.
    for backend, settings_scala, entries, calls_consumed in settings_files:
        spark = re.search(r"spark(\d)(\d)", module)
        spark = "%s.%s" % spark.groups() if spark else "?"
        path = os.path.join(out_dir, "settings-%s.txt" % backend)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(render_settings(entries, backend, spark))
        counts = {}
        for directive, _, _, _ in entries:
            counts[directive] = counts.get(directive, 0) + 1
        print("settings: %s (%s)" % (path, ", ".join(
            "%d %s" % (n, d) for d, n in sorted(counts.items(), key=lambda kv: -kv[1]))))

        # Independent cross-check: count the DSL call sites with a plain regex and
        # confirm the parser consumed every one of them. Test names themselves are
        # checked by VeloxSettingsMigrationSuite, which compares the run/skip
        # decision of the old and new settings for every name they mention.
        raw = strip_comments(open(settings_scala, encoding="utf-8").read())
        call_sites = len(re.findall(r"\.(%s)\(" % "|".join(DSL_TO_DIRECTIVE), raw))
        status = "OK" if call_sites == calls_consumed else "MISMATCH"
        print(
            "  cross-check: %d DSL call site(s) in Scala, %d consumed -- %s"
            % (call_sites, calls_consumed, status)
        )
        if status == "MISMATCH":
            return 1
    return 0


def cmd_generate(args):
    catalog = parse_catalog(args.catalog)
    written = 0
    for shell in catalog:
        target_dir = os.path.join(args.out, *shell.pkg.split("."))
        os.makedirs(target_dir, exist_ok=True)
        path = os.path.join(target_dir, "%s.scala" % shell.cls)
        content = render_shell(shell)
        if os.path.exists(path) and open(path, encoding="utf-8").read() == content:
            continue
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        written += 1
    print(
        "gluten-ut: %d suites in catalog, %d source file(s) written to %s"
        % (len(catalog), written, args.out)
    )
    return 0


def cmd_verify(args):
    """Prove the catalog reproduces the hand-written shells exactly."""
    module = args.module.rstrip("/")
    scala_root = os.path.join(module, "src/test/scala")
    symbols = scan_symbols([scala_root, os.path.join(module, "../common/src/test/scala")])
    # Keyed by the generated suite's own name: that is what the settings file and
    # the CI reports refer to. The base class is compared by simple name, because
    # a wildcard import in the source can leave its package ambiguous (see the
    # warning `extract` prints); a wrong package is caught by the compiler.
    def key(shell):
        return "%s.%s" % (shell.pkg, shell.cls)

    catalog = {key(s): s for s in parse_catalog(args.catalog)}
    existing = {}
    for path in scala_files(scala_root):
        text = open(path, encoding="utf-8").read()
        found, total = find_shells(path, text, symbols)
        for shell in found:
            if len(found) == total:
                existing[key(shell)] = shell

    missing = sorted(set(existing) - set(catalog))
    extra = sorted(set(catalog) - set(existing))
    differing = []
    for fqn, shell in sorted(existing.items()):
        gen = catalog.get(fqn)
        if gen is None:
            continue
        simple = lambda s: s.base_fqn.rsplit(".", 1)[-1]
        if (simple(gen), gen.traits, gen.anns) != (simple(shell), shell.traits, shell.anns):
            differing.append(fqn)

    print("verify: %d hand-written shells, %d in catalog" % (len(existing), len(catalog)))
    for label, items in (("missing from catalog", missing), ("not in sources", extra),
                         ("declaration differs", differing)):
        if items:
            print("  %s (%d):" % (label, len(items)))
            for item in items[:20]:
                print("    %s" % item)
    ok = not (missing or extra or differing)
    print("verify: %s" % ("OK -- catalog reproduces every shell" if ok else "FAILED"))
    return 0 if ok else 1


def cmd_prune(args):
    """Delete the hand-written sources the catalog now generates."""
    module = args.module.rstrip("/")
    scala_root = os.path.join(module, "src/test/scala")
    symbols = scan_symbols([scala_root, os.path.join(module, "../common/src/test/scala")])
    catalog = {"%s.%s" % (s.pkg, s.cls) for s in parse_catalog(args.catalog)}
    removable, kept = [], []
    for path in scala_files(scala_root):
        text = open(path, encoding="utf-8").read()
        found, total = find_shells(path, text, symbols)
        if not found:
            continue
        if len(found) == total and all(
            "%s.%s" % (s.pkg, s.cls) in catalog for s in found
        ):
            removable.append(path)
        else:
            kept.append(path)
    for path in removable:
        if args.apply:
            os.remove(path)
        print("%s %s" % ("removed" if args.apply else "would remove", path))
    print(
        "prune: %d file(s) %s, %d file(s) kept (shells mixed with other code)"
        % (len(removable), "removed" if args.apply else "to remove", len(kept))
    )
    if not args.apply:
        print("prune: re-run with --apply to delete them")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd")

    p = sub.add_parser("extract", help="Scala sources -> data files")
    p.add_argument("--module", required=True, help="e.g. gluten-ut/spark35")
    p.add_argument("--backends", nargs="+", default=["velox", "clickhouse", "bolt"])
    p.add_argument(
        "--settings-scala",
        help="read the settings from this file instead of the conventional path "
        "(useful once the original has been renamed, e.g. *TestSettingsLegacy.scala)",
    )
    p.set_defaults(func=cmd_extract)

    p = sub.add_parser("generate", help="catalog -> Scala sources")
    p.add_argument("--catalog", required=True)
    p.add_argument("--out", required=True)
    p.set_defaults(func=cmd_generate)

    p = sub.add_parser("verify", help="diff catalog against hand-written sources")
    p.add_argument("--module", required=True)
    p.add_argument("--catalog", required=True)
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("prune", help="delete hand-written sources the catalog now generates")
    p.add_argument("--module", required=True)
    p.add_argument("--catalog", required=True)
    p.add_argument("--apply", action="store_true", help="actually delete (default: dry run)")
    p.set_defaults(func=cmd_prune)

    args = parser.parse_args()
    if not args.cmd:
        parser.print_help()
        return 2
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
